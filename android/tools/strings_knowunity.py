def by_key() -> tuple[dict[str, dict[str, str]], dict[str, dict[str, dict[str, str]]]]:
    """Les phrases retournées clé par clé : `{clé: {langue: phrase}}`, et de même pour les pluriels."""
    strings: dict[str, dict[str, str]] = {}
    for locale, texts in BY_LANGUAGE.items():
        for key, text in texts.items():
            strings.setdefault(key, {})[locale] = text
    plurals: dict[str, dict[str, dict[str, str]]] = {}
    for locale, entries in PLURALS_BY_LANGUAGE.items():
        for key, forms in entries.items():
            plurals.setdefault(key, {})[locale] = forms
    return strings, plurals
