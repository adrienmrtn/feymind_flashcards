/** L'icône d'un pictogramme, ou l'ampoule quand le nom est inconnu. */
export function pathSymbolIcon(id: string | null | undefined): LucideIcon {
  const key = (id ?? "").trim().toLowerCase();
  return PATH_SYMBOL_ICONS[key] ?? PATH_SYMBOL_ICONS[DEFAULT_SYMBOL] ?? Lightbulb;
}
